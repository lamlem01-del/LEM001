def source_register():
    secs = json.load(open(os.path.join(HERE, "source_sections.json"), encoding="utf-8"))
    rows = []
    sid = 0
    for s in secs:
        if s["words"] == 0:
            continue
        sid += 1
        head = re.sub(r"\^\(\d+\)\^", "", s["heading"]).replace('\\"', '"').strip()
        rows.append([f"S{sid:02d}", head, s["words"], s["chars"], NOTES.get(s["i"], "")])
    write_csv("source-sections.csv",
              ["លេខផ្នែក", "ចំណងជើងក្នុងឯកសារ", "ពាក្យ (khmer-nltk)", "តួអក្សរខ្មែរ", "កំណត់សម្គាល់"], rows)
    total_w = sum(r[2] for r in rows)
    total_c = sum(r[3] for r in rows)
    md_rows = [[r[0], r[1], km(r[2]), km(r[3]), r[4]] for r in rows]
    md_rows.append(["**សរុប**", "", f"**{km(total_w)}**", f"**{km(total_c)}**", ""])
    text = (f"## ៨.៨ បញ្ជីផ្នែកនៃឯកសារគោល (S01–S{sid:02d})\n\n"
            "តារាងនេះបង្កើតដោយកម្មវិធី `tools/count_source_words.py` ពីច្បាប់ដែលអ្នកផ្តល់។ "
            "លេខ S ជាលេខយោងឌីជីថលបណ្តោះអាសន្ន ព្រោះឯកសារគ្មានលេខទំព័របោះពុម្ព។ "
            "ចំនួនពាក្យជាលទ្ធផលឧបករណ៍ មិនទាន់ក្រិតតាមការរាប់ដោយដៃ (មើលផ្នែក ១២)។\n\n"
            + md_table(["លេខ", "ចំណងជើងក្នុងឯកសារ", "ពាក្យ", "តួអក្សរ", "កំណត់សម្គាល់"], md_rows,
                       ["---", "---", "---:", "---:", "---"]))
    open(os.path.join(PHASE1, "08b-source-register.md"), "w", encoding="utf-8").write(text)
    return total_w, total_c


